/**
 * Auto-generate src/services/buildInfo.js with the current build time and git
 * commit. Run automatically before `npm run build` / `npm run release` via the
 * prebuild / prerelease npm lifecycle hooks.
 */
const fs = require('fs')
const path = require('path')
const { execSync } = require('child_process')

function sh(cmd) {
  try {
    return execSync(cmd, { encoding: 'utf8' }).trim()
  } catch (e) {
    return ''
  }
}

const root = path.join(__dirname, '..')

// Version (also available from manifest; kept here for convenience)
let version = '1.0.0'
try {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src', 'manifest.json'), 'utf8'))
  if (manifest.versionName) version = manifest.versionName
} catch (e) {}

// Short git commit hash (fallback to 'unknown' when not a git repo)
const commit = sh('git rev-parse --short HEAD') || 'unknown'

// Local build timestamp
const d = new Date()
const p = (n) => String(n).padStart(2, '0')
const buildTime = `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`

const content = `/**
 * Static build metadata shown on the 版本信息 (version info) page.
 * AUTO-GENERATED by scripts/update-buildinfo.js via the prebuild/prerelease
 * npm lifecycle hooks — do not edit by hand.
 */
export default {
  version: '${version}',
  buildTime: '${buildTime}',
  commit: '${commit}'
}
`

const out = path.join(root, 'src', 'services', 'buildInfo.js')
fs.writeFileSync(out, content)
console.log(`[buildinfo] updated ${path.relative(root, out)} → version=${version} buildTime=${buildTime} commit=${commit}`)
